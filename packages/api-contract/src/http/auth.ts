import { z } from 'zod';

import { IdSchema, IsoDateTimeSchema } from '../common.js';
import { UserProfileSchema } from '../models/user.js';

/**
 * `POST /api/v1/auth/login`
 *
 * The Rocket.Chat auth token never reaches the browser: the gateway exchanges
 * these credentials upstream and returns an opaque `HttpOnly` session cookie.
 *
 * Called again with a different `serverId` while already signed in, it adds a
 * connection to the existing session rather than replacing it — which is what
 * lets one client work across several Rocket.Chat servers.
 */
export const LoginRequestSchema = z.object({
  /** Which configured upstream to authenticate against. Omit when only one is configured. */
  serverId: IdSchema.optional(),
  /** Username or email; Rocket.Chat accepts either on the same field. */
  user: z.string().min(1),
  password: z.string().min(1),
  /** Six-digit TOTP, required after a `totp_required` error. */
  totpCode: z.string().optional(),
});
export type LoginRequest = z.infer<typeof LoginRequestSchema>;

/**
 * `POST /api/v1/auth/login/oauth`
 *
 * The second half of a Rocket.Chat OAuth sign-in. The browser runs the
 * provider handshake against the Rocket.Chat server itself — the gateway is
 * never an OAuth client and holds no provider secrets — and comes back with
 * the credential pair Rocket.Chat parked for that attempt. Exchanging it for
 * a session is the same step as a password login from here on.
 */
export const OAuthLoginRequestSchema = z.object({
  serverId: IdSchema.optional(),
  /** Generated by the client, echoed through the provider in `state`. */
  credentialToken: z.string().min(1),
  /** Handed back by Rocket.Chat once the provider handshake succeeded. */
  credentialSecret: z.string().min(1),
});
export type OAuthLoginRequest = z.infer<typeof OAuthLoginRequestSchema>;

/**
 * An OAuth provider a server offers on its login screen.
 *
 * Rocket.Chat splits this across a service record and a pile of settings, and
 * expects every client to know each provider's endpoints by heart. The gateway
 * does that resolution instead and advertises a ready-to-open authorization
 * URL, so a service only appears here when it can actually be signed in with.
 */
export const LoginServiceSchema = z.object({
  /** Rocket.Chat's service key — `google`, or the name of a custom OAuth entry. */
  id: z.string(),
  /** The provider's name, for a button that reads "Sign in with …". */
  title: z.string(),
  /**
   * Button text an administrator set for this service, which replaces the
   * whole sentence rather than filling in the provider name.
   */
  label: z.string().nullable(),
  /** Well-known provider name for icon lookup; null for custom services. */
  icon: z.string().nullable(),
  /** Button colours, set only by custom OAuth services and a few built-ins. */
  buttonColor: z.string().nullable(),
  buttonTextColor: z.string().nullable(),
  /**
   * The provider's authorization endpoint with everything filled in except
   * `state`, which carries the caller's own single-use credential token.
   */
  authorizeUrl: z.url(),
  /**
   * Where the provider sends the browser once the user has approved: always
   * Rocket.Chat's own callback, since it is Rocket.Chat that holds the client
   * secret. It is also where the resulting credential is left, so a client has
   * to be able to read that origin to finish the sign-in.
   */
  redirectUrl: z.url(),
});
export type LoginService = z.infer<typeof LoginServiceSchema>;

export const ConnectedServerSchema = z.object({
  id: IdSchema,
  name: z.string(),
  /** Public base URL of the Rocket.Chat server, for building deep links. */
  baseUrl: z.string(),
  version: z.string().nullable(),
});
export type ConnectedServer = z.infer<typeof ConnectedServerSchema>;

/**
 * One Rocket.Chat server this session is signed in to.
 *
 * A session holds several: the client stays connected to every one of them at
 * once — so unread counts keep moving on servers the user is not looking at —
 * and scopes each request to whichever is active.
 */
export const ServerConnectionSchema = z.object({
  user: UserProfileSchema,
  server: ConnectedServerSchema,
});
export type ServerConnection = z.infer<typeof ServerConnectionSchema>;

export const SessionSchema = z.object({
  /** Never empty: a session with no connections is deleted rather than kept. */
  connections: z.array(ServerConnectionSchema).min(1),
  /**
   * Which server requests without an explicit `X-Server-Id` header are scoped
   * to. The client sends the header, so this is mostly a safety net.
   */
  defaultServerId: IdSchema,
  expiresAt: IsoDateTimeSchema.nullable(),
});
export type Session = z.infer<typeof SessionSchema>;

/**
 * `POST /api/v1/auth/logout`
 *
 * Disconnects one server, or every one when `serverId` is omitted. Signing out
 * of the last server ends the session.
 */
export const LogoutRequestSchema = z.object({
  serverId: IdSchema.optional(),
});
export type LogoutRequest = z.infer<typeof LogoutRequestSchema>;

export const LoginResponseSchema = SessionSchema;
export type LoginResponse = z.infer<typeof LoginResponseSchema>;

/** `GET /api/v1/auth/session` — 401 when the cookie is missing or expired. */
export const SessionResponseSchema = SessionSchema;
export type SessionResponse = z.infer<typeof SessionResponseSchema>;

/**
 * `GET /api/v1/auth/servers` — public; lets a login screen offer a server
 * picker before any credentials exist.
 */
/**
 * A server as advertised before sign-in. The version is nullable here because
 * an unreachable server is still worth listing — it just cannot be probed.
 */
export const ServerDescriptorSchema = ConnectedServerSchema.omit({ version: true }).extend({
  version: z.string().nullable(),
  /**
   * Whether the server still accepts username and password. Rocket.Chat lets
   * an administrator turn the form off once SSO is in place, and a login
   * screen that kept showing it would be offering a door that is bolted shut.
   */
  passwordLoginEnabled: z.boolean(),
  /** OAuth providers the server has enabled, in the order they should be shown. */
  loginServices: z.array(LoginServiceSchema),
});
export type ServerDescriptor = z.infer<typeof ServerDescriptorSchema>;

export const ServerListResponseSchema = z.object({
  servers: z.array(ServerDescriptorSchema),
  defaultServerId: IdSchema.nullable(),
});
export type ServerListResponse = z.infer<typeof ServerListResponseSchema>;
